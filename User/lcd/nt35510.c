/**
 * @brief  在显示器上开辟一个窗口，并准备填充像素
 * @param  usX ：在特定扫描方向下窗口的起点X坐标
 * @param  usY ：在特定扫描方向下窗口的起点Y坐标
 * @param  usWidth ：窗口的宽度
 * @param  usHeight ：窗口的高度
 * @retval 无
 */
void NT35510_OpenWindow ( uint16_t usX, uint16_t usY, uint16_t usWidth, uint16_t usHeight )
{
	LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateX ); 				
	LCD_WRITE_DATA ( usX >> 8  );	
    LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateX + 1 ); 
	LCD_WRITE_DATA ( usX & 0xff  );	
    LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateX + 2 );
	LCD_WRITE_DATA ( ( usX + usWidth - 1 ) >> 8  );
    LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateX + 3 );
	LCD_WRITE_DATA ( ( usX + usWidth - 1 ) & 0xff  );

	LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateY ); 			  
	LCD_WRITE_DATA ( usY >> 8  );
    LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateY + 1);
	LCD_WRITE_DATA ( usY & 0xff  );
    LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateY + 2);
	LCD_WRITE_DATA ( ( usY + usHeight - 1 ) >> 8 );
    LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateY + 3);
	LCD_WRITE_DATA ( ( usY + usHeight - 1) & 0xff );

    LCD_WRITE_CMD ( NT35510_CMD_SetPixel );
}



void NT35510_Fill( uint16_t usX, uint16_t usY, uint16_t usWidth, uint16_t usHeight,uint16_t color )
{
	NT35510_OpenWindow ( usX, usY, usWidth, usHeight );   
    
    int temp =  usWidth * usHeight;
    		
	for (int  i = 0; i < temp; i ++ )
		LCD_WRITE_DATA ( color );	
	
}

uint32_t NT35510_ReadID(void)
{
	uint16_t ID[3];
    uint32_t id = 0;
	
    LCD_WRITE_CMD(0x0400); 
    ID[0] = LCD_READ_DATA();

    LCD_WRITE_CMD(0x0401); 
    ID[1] = LCD_READ_DATA();
    
    LCD_WRITE_CMD(0x0402); 
    ID[2] = LCD_READ_DATA();    
    id =  (ID[0]& 0xff) << 16 | (ID[1]& 0xff) << 8 | (ID[2]& 0xff);
	
    if(id == LCDID_NT35510)
    {
        return id;
    }
    else
    {
        return 0;
    }
}

