/**
 * @brief  设置显示器的GRAM的扫描方向 
 * @param  ucOption ：选择GRAM的扫描方向 
 *     @arg 0-7 :参数可选值为0-7这八个方向
 *
 *	！！！其中0、3、5、6 模式适合从左至右显示文字，
 *				不推荐使用其它模式显示文字	其它模式显示文字会有镜像效果			
 *		
 *	其中0、2、4、6 模式的X方向像素为480，Y方向像素为800
 *	其中1、3、5、7 模式下X方向像素为800，Y方向像素为480
 *
 *	其中 6 模式为大部分液晶例程的默认显示方向
 *	其中 3 模式为摄像头例程使用的方向
 *	其中 0 模式为BMP图片显示例程使用的方向
 *
 * @retval 无
 * @note  坐标图例：A表示向上，V表示向下，<表示向左，>表示向右
					X表示X轴，Y表示Y轴

							LCDID_NT35510
----------------------------------------------------------------------------
模式0：			.		模式1：		.	模式2：			.	模式3：					
			A	.			A		.		A			.		A									
			|	.			|		.		|			.		|							
			Y	.			X		.		Y			.		X					
			0	.			1		.		2			.		3					
	<--- X0 o	.	<----Y1	o		.		o 2X--->    .		o 3Y--->	
----------------------------------------------------------------------------	
模式4：			.	模式5：			.	模式6：			.	模式7：					
	<--- X4 o	.	<--- Y5 o		.		o 6X--->    .		o 7Y--->	
			4	.			5		.		6			.		7	
			Y	.			X		.		Y			.		X						
			|	.			|		.		|			.		|							
			V	.			V		.		V			.		V		
----------------------------------------------------------------------------				
						     LCD屏示例
						|-----------------|
						|	  野火Logo	  |
						|				  |
						|				  |
						|				  |
						|				  |
						|				  |
						|				  |
						|				  |
						|				  |
						|-----------------|
						屏幕正面（宽480，高800）
																			
 *******************************************************/
void NT35510_GramScan ( uint8_t ucOption )
{	
	//参数检查，只可输入0-7
	if(ucOption >7 )
		return;
	
	//根据模式更新LCD_SCAN_MODE的值，主要用于触摸屏选择计算参数
	LCD_SCAN_MODE = ucOption;
	
	//根据模式更新XY方向的像素宽度
	if(ucOption%2 == 0)	
	{
		//0 2 4 6模式下X方向像素宽度为480，Y方向为800
		NT35510_X_LENGTH = NT35510_LESS_PIXEL;
		NT35510_Y_LENGTH =	NT35510_MORE_PIXEL;
	}
	else				
	{
		//1 3 5 7模式下X方向像素宽度为800，Y方向为480
		NT35510_X_LENGTH = NT35510_MORE_PIXEL;
		NT35510_Y_LENGTH =	NT35510_LESS_PIXEL; 
	}

	//0x36命令参数的高3位可用于设置GRAM扫描方向	
	LCD_WRITE_CMD ( 0x3600 ); 

    LCD_WRITE_DATA ( 0x00 |(ucOption<<5));//根据ucOption的值设置LCD参数，共0-7种模式

	LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateX ); 
	LCD_WRITE_DATA ( 0x00 );		/* x 起始坐标高8位 */
    LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateX + 1 );
	LCD_WRITE_DATA ( 0x00 );		/* x 起始坐标低8位 */
    LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateX + 2 );
	LCD_WRITE_DATA ( ((NT35510_X_LENGTH-1)>>8)&0xFF ); /* x 结束坐标高8位 */	
	LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateX + 3 );
    LCD_WRITE_DATA ( (NT35510_X_LENGTH-1)&0xFF );				/* x 结束坐标低8位 */

	LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateY ); 
	LCD_WRITE_DATA ( 0x00 );		/* y 起始坐标高8位 */
	LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateY + 1 );
    LCD_WRITE_DATA ( 0x00 );		/* y 起始坐标低8位 */
	LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateY + 2 );
    LCD_WRITE_DATA ( ((NT35510_Y_LENGTH-1)>>8)&0xFF );	/* y 结束坐标高8位 */	 
	LCD_WRITE_CMD ( NT35510_CMD_SetCoordinateY + 3 );
    LCD_WRITE_DATA ( (NT35510_Y_LENGTH-1)&0xFF );				/* y 结束坐标低8位 */

	/* write gram start */
	LCD_WRITE_CMD ( NT35510_CMD_SetPixel );	
    
    //根据模式更新LCD X Y 的值
    LCD_X_LENGTH = NT35510_X_LENGTH;
    LCD_Y_LENGTH = NT35510_Y_LENGTH;
}

